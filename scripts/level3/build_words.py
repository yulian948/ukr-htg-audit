def main():
    inv, entries = load_inventory()
    apostrophes = [e for e in entries if e["group"] == "apostrophe"]
    units, errors = [], []
    for e in entries:
        ch = e["char"]
        if e["group"] == "alphabet":
            words = [(w, "сучасна лексика") for w in MODERN[ch]]
        elif e["group"] == "historical":
            words = HISTORICAL[ch]
        elif e["group"] == "apostrophe":
            words = [(f"п{ch}ять", "сучасна лексика"), (f"м{ch}ята", "сучасна лексика")]
        else:
            continue  # розділові знаки на рівні 3 не генеруємо
        for i, (w, src) in enumerate(words):
            w = unicodedata.normalize("NFC", w)
            if ch not in w:
                errors.append(f"{e['id']} «{ch}»: слово «{w}» його не містить")
            units.append({"unit": f"{e['id']}_w{i}", "entry_id": e["id"], "char": ch, "group": e["group"],
                          "word": w, "source": src})
    if errors:
        raise SystemExit("\n".join(errors))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({"inventory_version": inv["inventory_version"], "units": units},
                              ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    chars = sorted({c for u in units for c in u["word"]})
    print(f"{OUT.relative_to(ROOT)}: {len(units)} слів для {len(units) // 2} символів; "
          f"унікальних символів у словах: {len(chars)}")


if __name__ == "__main__":
    main()
